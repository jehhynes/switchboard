/** How far up the process tree the Codex process may be: a shell, then Codex (GC M40). */
export const PID_WALK_HOPS = 3;
/** The walk's limit, inside the hook's own timeout. */
export const PID_WALK_TIMEOUT_MS = 2_500;
/** The hook's timeout; Codex caps SessionEnd at 3 seconds. */
export const HOOK_TIMEOUT_SECONDS = 5;
export const SESSION_END_TIMEOUT_SECONDS = 3;
export const CONTRACT_TIMEOUT_SECONDS = 10;

/**
 * The events Switchboard's Codex hook records. The entries are synchronous: an asynchronous Stop hook did not run before a
 * background `exec` process exited (mechanics M31).
 */
export const CODEX_HOOK_EVENTS = ['SessionStart', 'UserPromptSubmit', 'PreToolUse', 'PermissionRequest', 'PostToolUse', 'Stop', 'SessionEnd'] as const;

/**
 * The Codex hook writer, installed as `<switchboard home>/codex-hook.mjs`. It writes `activity/<thread id>.json` beside itself,
 * with the identity of the Codex process that ran the hook, found once per turn and kept for the turn's later events. It always
 * exits 0 and prints nothing.
 */
export const CODEX_HOOK_SOURCE = `// Switchboard Codex session activity writer. Generated by Switchboard; edits are overwritten.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// The first codex process among the hook's nearest ancestors, with its creation time as the hub reads it.
function codexProcess() {
  if (process.platform !== 'win32') {
    return codexProcessFromProc();
  }

  const script = [
    '$id = ' + process.ppid,
    'for ($i = 0; $i -lt ${PID_WALK_HOPS} -and $id; $i++) {',
    '  $p = Get-CimInstance Win32_Process -Filter "ProcessId=$id"',
    '  if (-not $p) { break }',
    "  if ($p.Name.ToLower().Contains('codex')) { '' + $p.ProcessId + ' ' + $p.CreationDate.ToFileTimeUtc(); break }",
    '  $id = $p.ParentProcessId',
    '}',
  ].join('\\n');

  try {
    const [pid, created] = execFileSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', script], { encoding: 'utf8', timeout: ${PID_WALK_TIMEOUT_MS}, windowsHide: true }).trim().split(' ');
    const number = Number.parseInt(pid, 10);

    return Number.isInteger(number) && number > 0 && /^\\d+$/.test(created ?? '') ? { pid: number, created } : null;
  } catch {
    return null;
  }
}

// The creation time is the start time in clock ticks since boot, field 22 of /proc/<pid>/stat.
function codexProcessFromProc() {
  let id = process.ppid;

  for (let i = 0; i < ${PID_WALK_HOPS} && id > 1; i++) {
    let stat;

    try {
      stat = readFileSync('/proc/' + id + '/stat', 'utf8');
    } catch {
      return null;
    }

    const close = stat.lastIndexOf(')');
    const fields = stat.slice(close + 2).split(' ');

    if (stat.slice(stat.indexOf('(') + 1, close) === 'codex') {
      return /^\\d+$/.test(fields[19] ?? '') ? { pid: id, created: fields[19] } : null;
    }

    id = Number.parseInt(fields[1], 10);
  }

  return null;
}

try {
  const payload = JSON.parse(readFileSync(0, 'utf8'));
  const id = payload.session_id;
  const event = typeof payload.hook_event_name === 'string' ? payload.hook_event_name : null;

  // A debrief fork is not a session.
  if (process.env.FRICTION_DEBRIEF !== '1' && typeof id === 'string' && /^[A-Za-z0-9._-]+$/.test(id)) {
    const dir = fileURLToPath(new URL('./activity/', import.meta.url));
    const marker = dir + id + '.json';

    if (event === 'SessionEnd') {
      rmSync(marker, { force: true });
    } else {
      let held = null;

      try {
        held = JSON.parse(readFileSync(marker, 'utf8'));
      } catch {}

      // A turn's first events find the process; later ones keep it, because the walk takes about a second.
      const owner = event === 'SessionStart' || event === 'UserPromptSubmit' || held?.provider !== 'codex' || held?.pid == null ? codexProcess() : { pid: held.pid, created: held.created };
      const text = (value) => (typeof value === 'string' ? value : null);
      const tmp = marker + '.' + process.pid + '.tmp';

      mkdirSync(dir, { recursive: true });
      writeFileSync(tmp, JSON.stringify({
        v: 1,
        provider: 'codex',
        sessionId: id,
        event,
        at: Date.now(),
        source: text(payload.source),
        toolName: text(payload.tool_name),
        turnId: text(payload.turn_id),
        transcriptPath: text(payload.transcript_path),
        pid: owner?.pid ?? null,
        created: owner?.created ?? null,
      }));
      try {
        renameSync(tmp, marker);
      } catch {
        rmSync(tmp, { force: true });
      }
    }
  }
} catch {}

process.exit(0);
`;

export interface CodexMarker {
  sessionId: string;
  event: string | null;
  at: number;
  source: string | null;
  toolName: string | null;
  turnId: string | null;
  transcriptPath: string | null;
  pid: number | null;
  created: string | null;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** A Codex marker from its file text, or null for another provider's marker or an unreadable one. */
export function parseCodexMarker(text: string): CodexMarker | null {
  let value: unknown;

  try {
    value = JSON.parse(text);
  } catch {
    return null;
  }

  if (!isRecord(value) || value['provider'] !== 'codex' || typeof value['sessionId'] !== 'string' || typeof value['at'] !== 'number') {
    return null;
  }

  const optional = (key: string) => (typeof value[key] === 'string' ? value[key] : null);

  return {
    sessionId: value['sessionId'],
    event: optional('event'),
    at: value['at'],
    source: optional('source'),
    toolName: optional('toolName'),
    turnId: optional('turnId'),
    transcriptPath: optional('transcriptPath'),
    pid: typeof value['pid'] === 'number' ? value['pid'] : null,
    created: optional('created'),
  };
}

/** The state a Codex hook event gives: a running turn, a permission prompt, or the turn's end; null when the event sets none. */
export function codexMarkerState(marker: CodexMarker): 'running' | 'waiting' | 'idle' | null {
  switch (marker.event) {
    case 'UserPromptSubmit':
    case 'PreToolUse':
    case 'PostToolUse':
      return 'running';
    case 'SessionStart':
      return marker.source === 'compact' ? 'running' : null;
    case 'PermissionRequest':
      return 'waiting';
    case 'Stop':
      return 'idle';
    default:
      return null;
  }
}

function hookEntry(command: string, timeout: number): Record<string, unknown> {
  return { type: 'command', command, timeout };
}

/** The commands Switchboard installs, from the scripts' paths. */
export function codexHookCommands(hookPath: string, contractPath: string): { hook: string; contract: string } {
  return { hook: `node "${hookPath}"`, contract: `node "${contractPath}"` };
}

/**
 * The hooks.json text with Switchboard's entries added, `{unchanged: true}` when all are there, or why the file is left alone.
 * Other hooks are kept as they are; an earlier Switchboard entry with other settings is replaced in place.
 */
export function planCodexHooks(text: string | null, hookPath: string, contractPath: string): { text: string } | { unchanged: true } | { error: string } {
  let root: Record<string, unknown> = {};

  if (text !== null && text.trim() !== '') {
    try {
      const parsed: unknown = JSON.parse(text.replace(/^﻿/, ''));

      if (!isRecord(parsed)) {
        return { error: 'Codex hooks.json is not a JSON object, so Switchboard left it alone.' };
      }

      root = parsed;
    } catch {
      return { error: 'Codex hooks.json is not valid JSON, so Switchboard left it alone.' };
    }
  }

  if (root['hooks'] !== undefined && !isRecord(root['hooks'])) {
    return { error: 'The hooks entry of Codex hooks.json is not an object, so Switchboard left it alone.' };
  }

  const hooks: Record<string, unknown> = { ...((root['hooks'] as Record<string, unknown> | undefined) ?? {}) };
  const commands = codexHookCommands(hookPath, contractPath);
  const wanted: [string, string, number][] = [
    ...CODEX_HOOK_EVENTS.map((event): [string, string, number] => [event, commands.hook, event === 'SessionEnd' ? SESSION_END_TIMEOUT_SECONDS : HOOK_TIMEOUT_SECONDS]),
    ['SessionStart', commands.contract, CONTRACT_TIMEOUT_SECONDS],
  ];
  let changed = false;

  for (const [event, command, timeout] of wanted) {
    const groups = hooks[event] === undefined ? [] : hooks[event];

    if (!Array.isArray(groups)) {
      return { error: `The ${event} entry of Codex hooks.json is not a list, so Switchboard left it alone.` };
    }

    const entry = hookEntry(command, timeout);
    const index = groups.findIndex((group) => isRecord(group) && Array.isArray(group['hooks']) && group['hooks'].some((hook) => isRecord(hook) && hook['command'] === command));

    if (index === -1) {
      hooks[event] = [...groups, { hooks: [entry] }];
      changed = true;
      continue;
    }

    // Only Switchboard's entry is updated; the group's other entries and settings stay.
    const group = groups[index] as Record<string, unknown> & { hooks: unknown[] };
    const entries = group.hooks.map((hook) => (isRecord(hook) && hook['command'] === command ? entry : hook));

    if (JSON.stringify(entries) !== JSON.stringify(group.hooks)) {
      hooks[event] = groups.map((other, at) => (at === index ? { ...group, hooks: entries } : other));
      changed = true;
    }
  }

  return changed ? { text: `${JSON.stringify({ ...root, hooks }, null, 2)}\n` } : { unchanged: true };
}
