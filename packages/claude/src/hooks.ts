import type { LiveState } from '@switchboard/core';

/** Longest error text a marker keeps. */
export const ERROR_MESSAGE_LIMIT = 500;

/**
 * The hook writer, installed as `<switchboard home>/hook.mjs`. It writes `activity/<session id>.json` beside itself.
 * It always exits 0 and prints nothing, because exit 2 or stdout would change the session (GC M20).
 */
export const HOOK_SOURCE = `// Switchboard session activity writer. Generated by Switchboard; edits are overwritten.
import { mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

try {
  const payload = JSON.parse(readFileSync(0, 'utf8'));
  const id = payload.session_id;

  // Subagent events carry the parent's session ID and would overwrite its state.
  if (typeof payload.agent_id !== 'string' && typeof id === 'string' && /^[A-Za-z0-9._-]+$/.test(id)) {
    const dir = fileURLToPath(new URL('./activity/', import.meta.url));
    const marker = dir + id + '.json';

    if (payload.hook_event_name === 'SessionEnd') {
      rmSync(marker, { force: true });
    } else {
      const failed = payload.hook_event_name === 'StopFailure';
      const text = (value) => (typeof value === 'string' ? value : null);
      const tmp = marker + '.' + process.pid + '.tmp';

      mkdirSync(dir, { recursive: true });
      writeFileSync(tmp, JSON.stringify({
        v: 1,
        sessionId: id,
        event: text(payload.hook_event_name),
        at: Date.now(),
        notificationType: text(payload.notification_type),
        source: text(payload.source),
        toolName: text(payload.tool_name),
        backgroundTasks: Array.isArray(payload.background_tasks) ? payload.background_tasks.length : 0,
        error: failed ? text(payload.error) : null,
        errorMessage: failed && typeof payload.last_assistant_message === 'string' ? payload.last_assistant_message.slice(0, ${ERROR_MESSAGE_LIMIT}) : null,
      }));
      renameSync(tmp, marker);
    }
  }
} catch {}

process.exit(0);
`;

/** Hook events and their matchers (GC M2, M20). `StopFailure` replaces `Stop` when a turn ends on an API error. */
export const HOOK_EVENTS: readonly (readonly [event: string, matcher: string | null])[] = [
  ['SessionStart', null],
  ['UserPromptSubmit', null],
  ['PostToolBatch', null],
  ['PermissionRequest', null],
  ['PermissionDenied', null],
  ['PreToolUse', 'AskUserQuestion|ExitPlanMode'],
  ['Elicitation', null],
  ['Notification', 'permission_prompt|worker_permission_prompt|agent_needs_input'],
  ['Stop', null],
  ['StopFailure', null],
  ['SessionEnd', null],
];

type Json = Record<string, unknown>;

function isObject(value: unknown): value is Json {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function isOurs(group: unknown, hookPath: string): boolean {
  return isObject(group) && Array.isArray(group['hooks']) && group['hooks'].some((entry) => isObject(entry) && Array.isArray(entry['args']) && entry['args'][0] === hookPath);
}

export type HookPlan = { text: string } | { unchanged: true } | { error: string };

/**
 * Adds Switchboard's hook entry to each event that lacks one, keeping every other entry, including Ground Control's.
 * `text` is the settings file's content, or null when it does not exist. Malformed settings are left alone.
 */
export function planHooks(text: string | null, hookPath: string): HookPlan {
  let settings: unknown = {};

  if (text !== null && text.trim() !== '') {
    try {
      settings = JSON.parse(text);
    } catch {
      return { error: 'Claude settings.json is not valid JSON, so Switchboard did not add its hooks.' };
    }
  }

  if (!isObject(settings) || (settings['hooks'] !== undefined && !isObject(settings['hooks']))) {
    return { error: 'Claude settings.json has an unexpected shape, so Switchboard did not add its hooks.' };
  }

  const hooks: Json = { ...((settings['hooks'] as Json | undefined) ?? {}) };
  let added = 0;

  for (const [event, matcher] of HOOK_EVENTS) {
    const groups = hooks[event] ?? [];

    if (!Array.isArray(groups)) {
      return { error: `Claude settings.json has an unexpected hooks.${event}, so Switchboard did not add its hooks.` };
    }

    if (!groups.some((group) => isOurs(group, hookPath))) {
      const entry = { type: 'command', command: 'node', args: [hookPath], async: true, timeout: 5 };
      hooks[event] = [...groups, matcher === null ? { hooks: [entry] } : { matcher, hooks: [entry] }];
      added++;
    }
  }

  return added === 0 ? { unchanged: true } : { text: `${JSON.stringify({ ...settings, hooks }, null, 2)}\n` };
}

/** A marker the hook writer left. */
export interface Marker {
  sessionId: string;
  event: string | null;
  notificationType: string | null;
  source: string | null;
  toolName: string | null;
  backgroundTasks: number;
  error: string | null;
  errorMessage: string | null;
}

const WAITING_TOOLS = new Set(['AskUserQuestion', 'ExitPlanMode']);
const WAITING_NOTIFICATIONS = new Set(['permission_prompt', 'worker_permission_prompt', 'agent_needs_input']);

/** The state a marker shows, with the error of a failed turn, or null for an event that says nothing about state (GC M2, M20). */
export function markerState(marker: Marker): { state: LiveState; detail: string | null } | null {
  switch (marker.event) {
    case 'UserPromptSubmit':
    case 'PostToolBatch':
    case 'PermissionDenied':
      return { state: 'running', detail: null };
    case 'SessionStart':
      return marker.source === 'compact' ? { state: 'running', detail: null } : null;
    case 'PermissionRequest':
    case 'Elicitation':
      return { state: 'waiting', detail: null };
    case 'PreToolUse':
      return marker.toolName !== null && WAITING_TOOLS.has(marker.toolName) ? { state: 'waiting', detail: null } : null;
    case 'Notification':
      return marker.notificationType !== null && WAITING_NOTIFICATIONS.has(marker.notificationType) ? { state: 'waiting', detail: null } : null;
    case 'Stop':
      return { state: marker.backgroundTasks > 0 ? 'running' : 'idle', detail: null };
    case 'StopFailure':
      return { state: 'failed', detail: marker.error ?? marker.errorMessage };
    default:
      return null;
  }
}
