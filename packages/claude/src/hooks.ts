import type { LiveState } from '@switchboard/core';
import { NODE_NAME, PERMISSION_PROMPT, scriptHome } from '@switchboard/core';

/** Longest error text a marker keeps. */
export const ERROR_MESSAGE_LIMIT = 500;

/**
 * The hook writer, installed as `<switchboard home>/hook.mjs`. It writes `activity/<session id>.json` beside itself.
 * It always exits 0 and prints nothing, because exit 2 or stdout would change the session (GC M20).
 */
export const HOOK_SOURCE = `// Switchboard session activity writer. Generated by Switchboard; edits are overwritten.
import { mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

try {
  const payload = JSON.parse(readFileSync(0, 'utf8'));
  const id = payload.session_id;

  // Subagent events carry the parent's session ID and would overwrite its state; a debrief fork is not a session.
  if (typeof payload.agent_id !== 'string' && process.env.FRICTION_DEBRIEF !== '1' && typeof id === 'string' && /^[A-Za-z0-9._-]+$/.test(id)) {
    const dir = fileURLToPath(new URL('./activity/', import.meta.url));
    const marker = dir + id + '.json';

    if (payload.hook_event_name === 'SessionEnd') {
      rmSync(marker, { force: true });
    } else {
      const failed = payload.hook_event_name === 'StopFailure';
      const text = (value) => (typeof value === 'string' ? value : null);
      const tmp = marker + '.' + process.pid + '.tmp';
      // The permission_prompt notification names no tool and replaces the permission request's marker, so it keeps the request's tool.
      let promptTool = payload.hook_event_name === 'PermissionRequest' ? text(payload.tool_name) : null;

      if (payload.hook_event_name === 'Notification') {
        try {
          const previous = JSON.parse(readFileSync(marker, 'utf8'));
          // A permission request written before the writer recorded promptTool still names its tool.
          promptTool = previous.event === 'PermissionRequest' ? (text(previous.promptTool) ?? text(previous.toolName)) : previous.event === 'Notification' ? text(previous.promptTool) : null;
        } catch {}
      }

      // A Code Mode session's process carries its launch (PRD R93). Its marker keeps the source of the SessionStart that began its session ID,
      // through later events and compaction, because the marker is replaced on each event, and only a clear, fork or resume source shows the held
      // process changed its ID (mechanics M73, M77).
      const launch = text(process.env.SWITCHBOARD_LAUNCH) || null;
      let startSource = null;

      if (launch !== null) {
        if (payload.hook_event_name === 'SessionStart' && payload.source !== 'compact') {
          startSource = ['clear', 'fork', 'resume'].includes(payload.source) ? payload.source : null;
        } else {
          try {
            startSource = text(JSON.parse(readFileSync(marker, 'utf8')).startSource);
          } catch {}
        }
      }

      mkdirSync(dir, { recursive: true });
      writeFileSync(tmp, JSON.stringify({
        v: 1,
        sessionId: id,
        event: text(payload.hook_event_name),
        at: Date.now(),
        cwd: text(payload.cwd),
        notificationType: text(payload.notification_type),
        source: text(payload.source),
        toolName: text(payload.tool_name),
        promptTool,
        backgroundTasks: Array.isArray(payload.background_tasks) ? payload.background_tasks.length : 0,
        error: failed ? text(payload.error) : null,
        errorMessage: failed && typeof payload.last_assistant_message === 'string' ? payload.last_assistant_message.slice(0, ${ERROR_MESSAGE_LIMIT}) : null,
        ...(launch === null ? {} : { launch, startSource }),
      }));
      // Two hooks of one session can race; Windows then refuses the rename, so the newer marker wins and the file goes.
      try {
        renameSync(tmp, marker);
      } catch {
        rmSync(tmp, { force: true });
      }
    }
  }
} catch {}

process.exit(0);
`;

/** How long the contract hook waits for the hub. */
export const CONTRACT_HOOK_WAIT_MS = 5_000;

/**
 * The contract hook, installed as `<switchboard home>/contract.mjs` and run on `SessionStart` after a compaction, which drops the
 * contract from the system prompt (mechanics M30, M31). It asks the hub for the session's contract and prints it as `additionalContext`;
 * for any other session or start, or when the hub does not answer, it prints nothing. Codex has no matcher, so the script checks the source.
 */
export const CONTRACT_HOOK_SOURCE = `// Switchboard report contract restorer. Generated by Switchboard; edits are overwritten.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

try {
  const payload = JSON.parse(readFileSync(0, 'utf8'));

  // A subagent event carries its parent's session ID.
  if (payload.source === 'compact' && typeof payload.agent_id !== 'string' && typeof payload.session_id === 'string') {
    const record = JSON.parse(readFileSync(fileURLToPath(new URL('./hub.json', import.meta.url)), 'utf8'));
    const response = await fetch('http://127.0.0.1:' + record.port + '/contract', {
      method: 'POST',
      headers: { Authorization: 'Bearer ' + record.token, 'Content-Type': 'application/json' },
      body: JSON.stringify({ nativeSessionId: payload.session_id }),
      signal: AbortSignal.timeout(${CONTRACT_HOOK_WAIT_MS}),
    });
    const contract = response.ok ? (await response.json()).contract : null;

    if (typeof contract === 'string') {
      process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: 'SessionStart', additionalContext: contract } }));
    }
  }
} catch {}

process.exit(0);
`;

/** Hook events and their matchers (GC M2, M20). `StopFailure` replaces `Stop` when a turn ends on an API error. */
export const HOOK_EVENTS: readonly (readonly [event: string, matcher: string | null])[] = [
  ['SessionStart', null],
  ['UserPromptSubmit', null],
  ['PostToolBatch', null],
  // Only the waiting tools: a parallel tool's result must not end another tool's permission wait.
  ['PostToolUse', 'AskUserQuestion|ExitPlanMode'],
  ['PostToolUseFailure', 'AskUserQuestion|ExitPlanMode'],
  ['PermissionRequest', null],
  ['PermissionDenied', null],
  ['PreToolUse', 'AskUserQuestion|ExitPlanMode'],
  ['Elicitation', null],
  ['Notification', 'permission_prompt|worker_permission_prompt|agent_needs_input'],
  ['Stop', null],
  ['StopFailure', null],
  ['SessionEnd', null],
];

type Json = Record<string, unknown>;

function isObject(value: unknown): value is Json {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** Whether an entry is one Switchboard wrote: Node.js running the script and nothing else, whichever Node.js it names. */
function isOurEntry(entry: unknown, hookPath: string): boolean {
  return (
    isObject(entry) &&
    typeof entry['command'] === 'string' &&
    NODE_NAME.test(entry['command']) &&
    Array.isArray(entry['args']) &&
    entry['args'].length === 1 &&
    entry['args'][0] === hookPath
  );
}

function isOurs(group: unknown, hookPath: string): group is Json & { hooks: unknown[] } {
  return isObject(group) && Array.isArray(group['hooks']) && group['hooks'].some((entry) => isOurEntry(entry, hookPath));
}

/** The Switchboard home of an entry that runs a Switchboard script from a home other than this hub's, or null. */
function otherHome(entry: unknown, own: readonly string[]): string | null {
  if (!isObject(entry) || typeof entry['command'] !== 'string' || !NODE_NAME.test(entry['command']) || !Array.isArray(entry['args']) || entry['args'].length !== 1) {
    return null;
  }

  const script = entry['args'][0];

  return typeof script === 'string' && !own.includes(script) ? scriptHome(script) : null;
}

export type HookPlan = { text: string } | { unchanged: true } | { error: string };

/**
 * Adds Switchboard's hook entries to each event that lacks them, keeping every other entry, including Ground Control's: the
 * activity writer to every event in {@link HOOK_EVENTS}, and the contract hook to `SessionStart` after compaction. The contract
 * hook runs synchronously, because Claude reads its output. An entry of Switchboard's, found by its script, gets `nodePath`
 * (`sessions.nodePath`) as its command. An entry that runs a script of another Switchboard home whose hub is gone (`stale`) is
 * removed, with its group when nothing else is left in it. `text` is the settings file's content, or null when it does not exist.
 * Malformed settings are left alone.
 */
export function planHooks(text: string | null, hookPath: string, contractPath: string, nodePath: string, stale: (home: string) => boolean = () => false): HookPlan {
  let settings: unknown = {};

  if (text !== null && text.trim() !== '') {
    try {
      settings = JSON.parse(text);
    } catch {
      return { error: 'Claude settings.json is not valid JSON, so Switchboard did not add its hooks.' };
    }
  }

  if (!isObject(settings) || (settings['hooks'] !== undefined && !isObject(settings['hooks']))) {
    return { error: 'Claude settings.json has an unexpected shape, so Switchboard did not add its hooks.' };
  }

  const hooks: Json = { ...((settings['hooks'] as Json | undefined) ?? {}) };
  let changed = 0;
  const isStale = (entry: unknown) => {
    const home = otherHome(entry, [hookPath, contractPath]);

    return home !== null && stale(home);
  };

  for (const [event, groups] of Object.entries(hooks)) {
    if (!Array.isArray(groups) || !groups.some((group) => isObject(group) && Array.isArray(group['hooks']) && group['hooks'].some(isStale))) {
      continue;
    }

    const kept = groups.flatMap((group) => {
      if (!isObject(group) || !Array.isArray(group['hooks']) || !group['hooks'].some(isStale)) {
        return [group];
      }

      const entries = group['hooks'].filter((entry) => !isStale(entry));

      return entries.length === 0 ? [] : [{ ...group, hooks: entries }];
    });

    if (kept.length === 0) {
      delete hooks[event];
    } else {
      hooks[event] = kept;
    }

    changed++;
  }

  const entries = [
    ...HOOK_EVENTS.map(([event, matcher]) => ({ event, matcher, path: hookPath, entry: { type: 'command', command: nodePath, args: [hookPath], async: true, timeout: 5 } })),
    { event: 'SessionStart', matcher: 'compact', path: contractPath, entry: { type: 'command', command: nodePath, args: [contractPath], timeout: 10 } },
  ];

  for (const { event, matcher, path, entry } of entries) {
    const groups = hooks[event] ?? [];

    if (!Array.isArray(groups)) {
      return { error: `Claude settings.json has an unexpected hooks.${event}, so Switchboard did not add its hooks.` };
    }

    const index = groups.findIndex((group) => isOurs(group, path));

    if (index === -1) {
      hooks[event] = [...groups, matcher === null ? { hooks: [entry] } : { matcher, hooks: [entry] }];
      changed++;
      continue;
    }

    // Only the command of Switchboard's entry changes; the group's other entries and the entry's other keys stay.
    const group = groups[index] as Json & { hooks: unknown[] };
    const entries = group.hooks.map((other) => (isOurEntry(other, path) && (other as Json)['command'] !== nodePath ? { ...(other as Json), command: nodePath } : other));

    if (entries.some((other, at) => other !== group.hooks[at])) {
      hooks[event] = groups.map((other, at) => (at === index ? { ...group, hooks: entries } : other));
      changed++;
    }
  }

  return changed === 0 ? { unchanged: true } : { text: `${JSON.stringify({ ...settings, hooks }, null, 2)}\n` };
}

/** A marker the hook writer left. */
export interface Marker {
  sessionId: string;
  event: string | null;
  /** When the hook wrote the marker. */
  at?: number;
  /** The session's working directory; markers written before Switchboard recorded it have none. */
  cwd?: string | null;
  notificationType: string | null;
  source: string | null;
  toolName: string | null;
  /** The tool of the permission request a `PermissionRequest` or a `Notification` after it waits on; markers from before Switchboard recorded it have none. */
  promptTool?: string | null;
  backgroundTasks: number;
  error: string | null;
  errorMessage: string | null;
  /** The `SWITCHBOARD_LAUNCH` of a Code Mode session's process; absent for other sessions (PRD R93). */
  launch?: string;
  /** For a Code Mode process: `clear`, `fork` or `resume` when a SessionStart of that source began this session ID, else null (mechanics M73). */
  startSource?: string | null;
}

/** The detail of a turn that ended while background tasks remain: the session is `running`, but not on a prompt or tool call. */
export const BACKGROUND_DETAIL = 'turn ended with background tasks';

const WAITING_TOOLS = new Set(['AskUserQuestion', 'ExitPlanMode']);
const WAITING_NOTIFICATIONS = new Set(['permission_prompt', 'worker_permission_prompt', 'agent_needs_input']);

/** A permission request for a tool other than a question or a plan is a permission prompt (mechanics M57). */
function permissionDetail(tool: string | null | undefined): string | null {
  return typeof tool === 'string' && !WAITING_TOOLS.has(tool) ? PERMISSION_PROMPT : null;
}

/**
 * The state a marker shows, with the error of a failed turn or `PERMISSION_PROMPT` for a tool call's permission prompt, or null for an event that
 * says nothing about state (GC M2, M20). Claude sends a `permission_prompt` notification after a question's permission request as well as a
 * tool call's, so that notification's detail comes from the request's tool, which the hook writer carries over (mechanics M57).
 */
export function markerState(marker: Marker): { state: LiveState; detail: string | null } | null {
  switch (marker.event) {
    case 'UserPromptSubmit':
    case 'PostToolBatch':
    case 'PermissionDenied':
      return { state: 'running', detail: null };
    // The operator answered a question or a plan, before the rest of its batch resolves.
    case 'PostToolUse':
    case 'PostToolUseFailure':
      return marker.toolName !== null && WAITING_TOOLS.has(marker.toolName) ? { state: 'running', detail: null } : null;
    case 'SessionStart':
      return marker.source === 'compact' ? { state: 'running', detail: null } : null;
    case 'PermissionRequest':
      return { state: 'waiting', detail: permissionDetail(marker.toolName) };
    case 'Elicitation':
      return { state: 'waiting', detail: null };
    case 'PreToolUse':
      return marker.toolName !== null && WAITING_TOOLS.has(marker.toolName) ? { state: 'waiting', detail: null } : null;
    case 'Notification':
      // A notification written before the writer recorded promptTool cannot tell its wait, so the roster's waitingFor decides.
      if (marker.notificationType === 'permission_prompt') {
        return marker.promptTool === undefined ? null : { state: 'waiting', detail: permissionDetail(marker.promptTool) };
      }

      // A subagent's permission prompt: the hook writer skips subagent events, so its permission request leaves no marker.
      if (marker.notificationType === 'worker_permission_prompt') {
        return { state: 'waiting', detail: PERMISSION_PROMPT };
      }

      return marker.notificationType !== null && WAITING_NOTIFICATIONS.has(marker.notificationType) ? { state: 'waiting', detail: null } : null;
    case 'Stop':
      return marker.backgroundTasks > 0 ? { state: 'running', detail: BACKGROUND_DETAIL } : { state: 'idle', detail: null };
    case 'StopFailure':
      return { state: 'failed', detail: marker.error ?? marker.errorMessage };
    default:
      return null;
  }
}
